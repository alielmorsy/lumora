import fs from "node:fs/promises";
import path from "node:path";

const NAME = /^[A-Z][A-Za-z0-9]*$/;
const slash = (p) => p.replaceAll("\\", "/");
const exists = (p) => fs.access(p).then(() => true, () => false);
const ls = (dir) => fs.readdir(dir).catch(() => []);

async function packageDirs(root) {
  const nm = path.join(root, "node_modules");
  const dirs = [root];
  for (const e of await ls(nm)) {
    if (e.startsWith("@")) for (const s of await ls(path.join(nm, e))) dirs.push(path.join(nm, e, s));
    else if (!e.startsWith(".")) dirs.push(path.join(nm, e));
  }
  return dirs;
}

async function resolveDir(pkgDir, field, label, name) {
  const dir = path.resolve(pkgDir, field.dir ?? "");
  if (!(await exists(dir))) throw new Error(`Module "${name}": ${label} dir not found: ${dir}`);
  return dir;
}

export async function discoverModules(root) {
  const seen = new Set();
  const byName = new Map();
  for (const candidate of await packageDirs(root)) {
    let packageDir;
    try {
      packageDir = await fs.realpath(candidate);
    } catch {
      continue;
    }
    if (seen.has(packageDir)) continue;
    seen.add(packageDir);
    let pkg;
    try {
      pkg = JSON.parse(await fs.readFile(path.join(packageDir, "package.json"), "utf8"));
    } catch {
      continue;
    }
    const l = pkg.lumora;
    if (!l) continue;
    const packageName = pkg.name ?? path.basename(packageDir);
    const name = l.module;
    if (typeof name !== "string" || !NAME.test(name)) throw new Error(`${packageName}: invalid native module name "${name}" (expected ${NAME})`);
    if (!l.cpp && !l.android) throw new Error(`${packageName}: module "${name}" needs a cpp or android entry`);
    const info = { name, packageName, packageDir };
    if (l.cpp) {
      const dir = await resolveDir(packageDir, l.cpp, "cpp", name);
      if (!(await exists(path.join(dir, "CMakeLists.txt")))) throw new Error(`Module "${name}" (${packageName}): ${dir} has no CMakeLists.txt`);
      if (!l.cpp.target) throw new Error(`Module "${name}" (${packageName}): cpp.target is required`);
      info.cpp = { dir, target: l.cpp.target };
    }
    if (l.android) {
      if (!l.android.class) throw new Error(`Module "${name}" (${packageName}): android.class is required`);
      info.android = { dir: await resolveDir(packageDir, l.android, "android", name), className: l.android.class };
    }
    const prev = byName.get(name);
    if (prev) throw new Error(`Duplicate native module "${name}" in packages ${prev.packageName} and ${packageName}`);
    byName.set(name, info);
  }
  return [...byName.values()].sort((a, b) => (a.name < b.name ? -1 : 1));
}

async function writeIfChanged(file, text) {
  if ((await fs.readFile(file, "utf8").catch(() => null)) === text) return false;
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, text);
  return true;
}

export async function writeDesktopLinkFiles(root, modules) {
  const dir = path.join(root, ".lumora", "native");
  const cmakeFile = path.join(dir, "modules.cmake");
  const genFile = path.join(dir, "LinkedModules.gen.cpp");
  const linked = modules.filter((m) => m.cpp);

  const cmake = [
    "# Generated by lumora. Do not edit.",
    ...linked.map((m) => `add_subdirectory("${slash(m.cpp.dir)}" "\${CMAKE_BINARY_DIR}/lumora_modules/${m.name}")`),
    `set(LUMORA_JS_MODULE_TARGETS ${linked.map((m) => m.cpp.target).join(" ")})`,
    `set(LUMORA_JS_MODULES_SOURCE "${slash(genFile)}")`,
    "",
  ].join("\n");

  const gen = [
    "// Generated by lumora. Do not edit.",
    "#include <lumora/script/NativeModule.h>",
    "",
    ...linked.map((m) => `LUMORA_NATIVE_MODULE(${m.name});`),
    "",
    "void lumora::script::RegisterLinkedModules(ModuleRegistry& registry)",
    "{",
    ...linked.map((m) => `    registry.Add("${m.name}", &LumoraModule_${m.name}_Install);`),
    "}",
    "",
  ].join("\n");

  const a = await writeIfChanged(cmakeFile, cmake);
  const b = await writeIfChanged(genFile, gen);
  return { cmakeFile, changed: a || b };
}
